std::string defaultOf(const PropSpec& p) {
  switch (p.kind) {
    case PropSpec::Bool: return p.def != 0 ? "`true`" : "`false`";
    case PropSpec::Number: return p.integer ? std::format("`{}`", static_cast<long>(p.def)) : std::format("`{}`", p.def);
    default: return "`\"" + p.defText + "\"`";
  }
}

std::string valuesOf(const PropSpec& p) {
  switch (p.kind) {
    case PropSpec::Bool: return "`true` / `false`";
    case PropSpec::Number:
      return p.integer ? std::format("{} – {}", static_cast<long>(p.min), static_cast<long>(p.max))
                       : std::format("{} – {}", p.min, p.max);
    case PropSpec::Text: return "text";
    case PropSpec::Color: return "palette role (`primary`, `secondary`, `tertiary`, `on_surface`, …) or `#rrggbb`";
    case PropSpec::Enum: {
      std::string s;
      for (const auto& o : p.options) s += (s.empty() ? "" : ", ") + ("`" + o + "`");
      return s;
    }
    default: break;
  }
  return {};
}

void table(std::string& md, const std::string& type) {
  md += "| Key | Values | Default | |\n|---|---|---|---|\n";
  for (const auto& p : schemaFor(type))
    md += std::format("| `{}` | {} | {} | {} |\n", p.key, valuesOf(p), defaultOf(p), p.labelEn);
}
