std::string optionsMarkdown() {
  std::string md;
  md += "# Configuration options\n\n";
  md += "<!-- generated by `undershell --doc` from src/schema.hpp; tests/test_docs.cpp checks it -->\n\n";
  md += "`~/.config/undershell/config.toml` is applied live when saved. Everything here can\n";
  md += "also be changed from the editor's inspector (`undershell msg edit`).\n\n";
  md += "## `[general]`\n\n";
  md += "| Key | Values | Default | |\n|---|---|---|---|\n";
  md += "| `grid` | px | `16` | editor snap step |\n";
  md += "| `noise_reduction` | 0 – 1 | `0.45` | analyser smoothing (Ryoku's cava used 45) |\n";
  md += "| `monstercat` | `true` / `false` | `false` | spread peaks to neighbours |\n";
  md += "| `language` | `system`, `en`, `es` | `\"system\"` | editor language; `system` follows the locale (Spanish under `es_*`, else English). Also switchable in the editor's help card |\n";
  md += "| `wallpaper` | path | `\"\"` | the wallpaper, when neither Noctalia nor KDE Plasma says which it is (or to override them): depth and per-wallpaper layouts follow it |\n";
  md += "| `wallpaper_fill` | `center`, `crop`, `fit`, `stretch`, `repeat` | the source's, else `crop` | how that wallpaper is fitted to the screen |\n";
  md += "| `depth_model` | `true` / `false` | `true` | compute each wallpaper's depth with undershell's model (Depth Anything V2), once it has been downloaded (the inspector's button or `undershell msg depth-model`; a copy Noctalia's `wallpaper_depth` already has is used); `false` turns depth off |\n";
  md += "| `depth_threshold` | 0 – 100 | Noctalia's `wallpaper_depth` threshold, else `30` | the depth plane of widgets with `depth_level = 0`: higher is nearer, so less of the wallpaper covers them |\n";
  md += "| `depth_feather` | 0 – 100 | Noctalia's `wallpaper_depth` feather, else `8` | how soft the edge of every depth cut is |\n\n";
  md += "## Every `[[widget]]`\n\n";
  md += "| Key | Values | Default | |\n|---|---|---|---|\n";
  md += "| `id` | text | type name | unique name (used by `msg set/select/remove`) |\n";
  md += "| `type` | `visualizer`, `clock`, `now_playing`, `shape`, `image`, `text`, `lyrics`, `calendar`, `notes`, `weather` | `\"visualizer\"` | |\n";
  md += "| `output` | connector (`HDMI-A-1`, `eDP-1`, …) | first output | monitor |\n";
  md += "| `x`, `y` | logical px | `0` | position on the output (may hang off an edge) |\n";
  md += "| `space` | `[w, h]` | the screen it is first shown on | the output size (logical px) the layout was made on; `x`, `y`, `width`, "
        "`height` and `pin` are in it. On a screen of another size or scale the widget follows the wallpaper (its fill mode), not "
        "the screen. Written by the editor; a block without it is given the size of the screen it first appears on |\n";
  md += "| `width`, `height` | logical px | `800` × `240` | box; the design is fitted into it |\n";
  md += "| `enabled` | `true` / `false` | `true` | |\n";
  md += "| `name` | text | the id | what the editor's Layers panel calls it |\n";
  md += "| `group` | text | none | widgets with the same group are selected, moved, scaled, turned, hidden and locked together "
        "(the Layers panel's Group, Ctrl+G) |\n";
  md += "| `hidden` | `true` / `false` | `false` | not shown at all: no surface, nothing drawn (the eye in the Layers panel) |\n";
  md += "| `locked` | `true` / `false` | `false` | cannot be picked or moved on the desktop; still selectable in the Layers panel |\n";
  md += "| `depth` | `true` / `false` | `true` | pass behind what stands in front in the wallpaper (its depth plane: `depth_level`) |\n\n";
  md += "## `type = \"visualizer\"`\n\nRyoku's desktop spectrum.\n\n";
  table(md, "visualizer");
  md += "\n## `type = \"clock\"`\n\nRyoku's clock faces and date strips.\n\n";
  table(md, "clock");
  md += "\n## `type = \"now_playing\"`\n\nRyoku's now-playing card.\n\n";
  table(md, "now_playing");
  md += "| `music_app` | shell command | `\"spotify\"` | opened by the corner button (not in the inspector) |\n";
  md += "\n## `type = \"shape\"`\n\nA geometric shape, to build compositions out of layers.\n\n";
  table(md, "shape");
  md += "\n## `type = \"image\"`\n\nA picture, a sticker, a GIF or a video, with its transparency.\n\n";
  md += "| Key | Values | Default | |\n|---|---|---|---|\n";
  md += "| `file` | path (`~/` allowed) | `\"\"` | PNG, JPG, GIF, WebP, APNG or a video (the inspector's Choose button) |\n";
  {
    std::string rest;
    table(rest, "image");
    md += rest.substr(rest.find("|---|---|---|---|\n") + 18);
  }
  md += "\n## `type = \"text\"`\n\nWords with effects. In `text`, `{title}`, `{artist}` and `{album}` are the song playing, "
        "`{time}`, `{date}` and `{day}` the clock; `\\n` starts a new line. A `style` sets the keys after `font`; a key "
        "the block sets wins over its style. The defaults below are the `plain` style's.\n\n";
  table(md, "text");
  md += "\n## `type = \"lyrics\"`\n\nThe synced lyrics of the song playing (LRCLIB), with the text widget's styles and "
        "effects; the keys after `style` are the text widget's.\n\n";
  table(md, "lyrics");
  md += "\n## `type = \"calendar\"`\n\nThe month, the week, today's page or an agenda, today in the accent colour. Events are "
        "read from this computer only (never fetched): `.ics` files or folders of them (`ics`, separated by `;`), khal's calendars "
        "(its config's vdirs) and Evolution's / GNOME Calendar's (local ones, and the copies it keeps of online ones; hidden or "
        "disabled ones are left out). They are watched, and Evolution's cache looked at every 10 minutes.\n\n";
  table(md, "calendar");
  md += "| `date` | `YYYY-MM-DD` | `\"\"` | shows that day instead of today (not in the inspector) |\n";
  md += "\n## `type = \"notes\"`\n\nA note kept in a Markdown file (headings, lists, `- [ ]` tasks ticked with a click), "
        "typed on in the editor (double-click it) or in any text editor; the file is watched.\n\n";
  table(md, "notes");
  md += "| `file` | path (`~/` allowed) | `\"\"` | the Markdown file; empty: `~/.local/share/undershell/notes/<id>.md` |\n";
  md += "\n## `type = \"weather\"`\n\nThe weather from Open-Meteo (no account or key) for the `location` you write: a city "
        "(sent once to Open-Meteo's geocoding) or `\"lat, lon\"`. Only coordinates rounded to 0.01° are sent after that, every "
        "half hour; answers are cached in `~/.cache/undershell/weather`.\n\n";
  table(md, "weather");
  return md;
}

